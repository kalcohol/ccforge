def failure_manifest():
    names=[x for x in Path(__file__).with_name('sensitivity.txt').read_text().splitlines() if x and not x.startswith('#')]
    if names!=sorted(set(names)): raise ValueError('sensitivity names must be sorted and unique')
    return frozenset(names)
def declared(t):
    fail=t['name'] in failure_manifest()
    if t['control'] and fail!=CONTROLS[t['control']]['fail']: raise ValueError('control declaration mismatch')
    return fail

